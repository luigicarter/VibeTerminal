'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const file = path.resolve(__dirname, '../../frontend/components/orchestratorWorkHistoryModel.ts');
const helper = new Module(file, module);
helper._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, file);
const { workProjects, filterWorkHistory } = helper.exports;
const base = { id: '1', cwd: 'C:\\Projects\\API', projectName: 'API', title: 'Fixed routes', terminalName: 'Code', provider: 'codex', summary: 'Unit tests passed', status: 'completed', completedAt: 100 };
const records = [base, { ...base, id: '2', cwd: 'c:/projects/api/', completedAt: 200, status: 'failed' }, { ...base, id: '3', cwd: 'C:\\Other\\API', completedAt: 300 }];
assert.equal(workProjects(records).length, 2, 'Same name in different paths remains separate projects');
assert.deepEqual(filterWorkHistory(records, '').map(record => record.id), ['3', '2', '1']);
assert.deepEqual(filterWorkHistory(records, 'c:/projects/api').map(record => record.id), ['2', '1']);
assert.equal(filterWorkHistory(records, 'c:/projects/ap').length, 0);
assert.deepEqual(filterWorkHistory(records, 'c:/projects/api', 'FAILED').map(record => record.id), ['2']);
assert.equal(filterWorkHistory(records, '', 'unit tests').length, 3);
assert.equal(filterWorkHistory(records, '', 'absent').length, 0);
assert.deepEqual(records.map(record => record.id), ['1', '2', '3'], 'Filtering must not mutate snapshot order');
console.log('Orchestrator work history project/filter smoke passed.');
